-- OpenGreenTrack テスト/デモ専用シード（supabase/seeds/demo/demo.sql）
--
-- 本番環境には投入しないこと。デモ組織・固定パスワードのデモユーザー・架空の活動量/排出量など、
-- 画面確認・E2E・算定エンジン検証のためのデータだけを収録する。
-- 登場する会社名・人名・住所・法人番号・電話番号はすべて架空で、実在の企業・人物とは関係ない
-- （公式の公表資料名・URL と排出係数の出典だけは実在のものを参照する）。
-- 実在の値と紛れないよう、識別子は「制度上ありえない値」を使う:
--   社名       組織・サプライヤーとも「架空」を冠する（架空精密工業株式会社 など）。それらしい社名は
--              同名の実在企業がありうるため使わない
--   人名       「環境 太郎」形式（姓＝役割や拠点の機能、名＝太郎/花子/一郎…）。ありふれた実在の姓名は使わない
--   拠点名     「東京本社」「名古屋工場」のような一般的な呼称。地名は実在するが特定の事業所を指すものではなく、
--              住所は上記のとおり存在しない（locations.region と地名を揃えて地域別の見え方を確認できるようにする）
--   法人番号   1111111111111 / 2222222222222 … 13桁の形式は満たすが検査数字が不正（正しくは先頭9）で発番されえない
--   住所       「架空区」「架空市」「架空町」… 日本に存在しない自治体名。都道府県だけは実在のものを残す
--              （locations.region が地域一致の係数解決に効くため、拠点の所在地域と矛盾させない）
--   電話番号   000-000-000N … 市外局番は 0 の次に 1〜9 が来るため、000 で始まる番号は実在しない
--   メール     example.com（RFC 2606 の予約ドメイン）
--
-- `supabase db reset` では自動投入されない（config.toml の [db.seed].sql_paths は
-- seeds/production/ のみ）。必要なときだけ明示的に流す:
--   ローカル DB 作り直し + デモ : npm run db:reset:demo
--     （= npx supabase db reset --sql-paths "./seeds/production/*.sql" --sql-paths "./seeds/demo/*.sql"）
--   稼働中ローカル DB へ投入    : npm run db:seed:demo
--     （= node scripts/db/seed.ts demo。ローカル Supabase の DB コンテナ内で psql により実行する）
--   クラウド（開発/検証プロジェクトのみ）: Dashboard の SQL Editor でこのファイルを実行する。
--     ホストに psql があれば npm run db:seed:demo -- --db-url postgresql://… --force でも可
--     （リモート DB へのデモ投入は誤投入防止のため --force が無いと拒否される）。本番プロジェクトでは行わない。
--
-- 冪等性: デモ組織 3 社（下記）を先頭で削除してから入れ直す（削除→再投入）。何度流しても同じ状態になり、
-- デモ組織に手で追加したデータ（E2E が作ったレコードを含む）は再投入で消える。
-- 本番マスタ seed（seeds/production/official_emission_factors.sql）とは互いに依存しない:
-- 単独でも、production の前後どちらに流しても動く（2025・2026 年度の算定結果が参照する公式係数 ID は
-- 「あれば参照し、無ければ null」で埋め、係数の値・単位・名称は appliedFactor* にスナップショットで持つ）。
--
-- デモ組織とログインアカウント（パスワードはすべて password123）:
--   架空精密工業株式会社（メインのデモ組織。電子部品メーカー、国内 12 拠点 + 海外 1）
--     org-a@example.com      環境 太郎（admin）
--     member-a@example.com   算定 花子（logger）
--     member2-a@example.com  報告 次郎（viewer）
--   架空ロジスティクス株式会社（別組織。組織分離＝RLS の確認用。北海道の物流会社、3 拠点）
--     org-b@example.com      物流 太郎（admin）
--   架空検証株式会社（ログイン不可。POST /api/calculations の算定エンジン検証専用。(10) 参照）
--
-- 収録データの期間: 2023 年度〜2026 年度（会計年度は 4 月始まり）。
--   2023〜2025 年度は 12 か月分、2026 年度は当年度進行中として 4〜8 月分の月次活動量を持つ。
--   月次活動量は拠点 × 種別ごとの基準値 × 季節変動 × 年度トレンド（毎年数 % 減）で決定的に生成する。
--   算定結果・年度集計・レポート履歴の数値はすべて活動量から導出するため互いに整合する。
--
-- E2E スモークテスト（e2e/support/testData.ts）が前提にしていること。変更するときは testData.ts も直す:
--   - org-a@example.com / password123 でログインできる
--   - 拠点「大阪支社」は稼働中で、2024 年度（2024-04〜2025-03）の電気レコードを持たない
--     （大阪支社は 2025 年度から算定対象に加わった設定。E2E はここへ 2024-11 / 12 / 2025-01 を保存する）
--   - 2024 年度に自動解決される電気の係数は「電気 代替値（全国）2024 年度」= 0.000434 t-CO2/kWh の 1 件だけ
--   - 既定で選ばれる年度は最新の 2026 年度（E2E は別年度 2024 年度へ切り替えて検証する）
--
-- 収録セクション:
--   (1) 組織・ユーザー   (2) 会計年度   (3) 拠点   (4) 排出係数
--   (5) 月次活動量・算定結果・算定バッチ   (6) Scope3（サプライヤー・カテゴリ別）   (7) 削減目標
--   (8) 年度集計の再計算   (9) レポート出力履歴・招待   (10) 算定エンジン検証用組織
